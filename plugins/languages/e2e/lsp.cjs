// Code navigation with gopls through the language pack lang-go (#146), its server confined
// (skipped when gopls is not installed).
const { execSync } = require('child_process')
const fs = require('fs')
const path = require('path')
const { run, openProject, open, assert, text, installOfficial, OUT, WS } = require('../../../e2e/common.cjs')
try {
  execSync('command -v gopls', { env: { ...process.env, PATH: process.env.HOME + '/go/bin:' + process.env.PATH }, stdio: 'ignore' })
} catch {
  console.log('  (gopls not installed: suite skipped)')
  process.exit(0)
}
run(async ({ page }) => {
  const lock = await installOfficial('lang-go')
  assert(lock?.grants.join() === 'program:gopls,path:GOROOT,path:GOMODCACHE', 'lang-go installed with its grants: ' + JSON.stringify(lock))
  // A file with one private and one exported function (the lock of Structure, #170), and a third
  // one the suite never opens in an editor (the package view reads it through the server, #172).
  fs.writeFileSync(path.join(WS, 'demo/src/priv.go'), 'package main\n\nfunc maxFrame() int { return 1024 }\n\nfunc Transport() string { return "tcp" }\n')
  fs.writeFileSync(path.join(WS, 'demo/src/silent.go'), 'package main\n\nfunc Silent() string { return "not opened" }\n')
  await openProject(page)
  await open(page, 'main.go')
  const caretOn = async (needle, delta = 1) => {
    await page.evaluate(([needle, delta]) => {
      const pre = document.querySelector('.pane.active .ed-content')
      pre.focus()
      for (const block of pre.children) {
        const node = block.firstChild
        const i = node.data.indexOf(needle)
        if (i >= 0) { getSelection().setBaseAndExtent(node, i + delta, node, i + delta); break }
      }
    }, [needle, delta])
    await page.waitForTimeout(100)
  }
  const line = () => page.textContent('[data-testid=status-cursor]')
  // gopls starts cold (module loading): Ctrl+B is retried until it answers.
  let jumped = false
  for (let i = 0; i < 20 && !jumped; i++) {
    await caretOn('.Hello())', 2)
    await page.keyboard.press('Control+b')
    jumped = await page.waitForFunction(() => document.querySelector('[data-testid=status-cursor]')?.textContent.startsWith('8:'), null, { timeout: 1500 }).then(() => true, () => false)
  }
  assert(jumped, 'Ctrl+B goes to the declaration (line 8): ' + (await line()))
  // On the declaration: the usages (a single one: jump to it).
  await page.keyboard.press('Control+b')
  const usages = await page.waitForFunction(() => document.querySelector('[data-testid=status-cursor]')?.textContent.startsWith('13:') || document.querySelector('.pick'), null, { timeout: 8000 }).then(() => true, () => false)
  assert(usages, 'Ctrl+B on the declaration shows the usages')
  await page.keyboard.press('Escape')
  await page.click('.rail-right .rail-btn[title="Structure"]')
  const syms = await page
    .waitForFunction(() => {
      const names = [...document.querySelectorAll('.side-right .tree-row .tree-name')].map((x) => x.textContent)
      return names.includes('Greeter') && names.some((n) => n.includes('Hello')) && names
    }, null, { timeout: 8000 })
    .then((h) => h.jsonValue(), () => [])
  assert(syms.length > 0, 'the structure lists the symbols ' + JSON.stringify(syms))
  // The VS Code look: the glyph in a colored disc, the twisty, the folding, the sort, the clicks.
  const row = (name) => `.side-right .tree-row:has(.tree-name:text-is("${name}"))`
  const names = () => page.$$eval('.side-right .tree-row .tree-name', (e) => e.map((x) => x.textContent))
  const glyph = await page.$eval(row('Greeter') + ' .sym-glyph', (e) => ({
    text: e.textContent,
    color: getComputedStyle(e).color,
    bg: getComputedStyle(e).backgroundColor,
  }))
  assert(/[A-Za-z]/.test(glyph.text) && glyph.bg !== 'rgba(0, 0, 0, 0)', 'the glyph of Greeter sits in a colored disc: ' + JSON.stringify(glyph))
  assert(!!(await page.$(row('Greeter') + ' .tree-twist.open')), 'Greeter has a twisty')
  await page.click(row('Greeter') + ' .tree-twist')
  await page.waitForTimeout(300)
  assert(!(await names()).includes('Name'), 'the twisty folds the field under Greeter: ' + JSON.stringify(await names()))
  // The head of the Structure tool holds its title only: its four buttons sit in the corner group
  // of its zone, before the ⋮ (#176).
  assert(!(await page.$$('.structure .panel-head button').length), 'no button left in the head of the Structure tool')
  const structureCorner = await page.$$eval('[data-tool=structure] .zone-corner button', (b) => b.map((x) => x.getAttribute('data-testid')))
  assert(
    JSON.stringify(structureCorner) === JSON.stringify(['structure-expand', 'structure-collapse', 'structure-search', 'structure-refresh', 'zone-menu']),
    'the corner group of the Structure zone: ' + JSON.stringify(structureCorner),
  )
  await page.click('[data-testid=structure-expand]')
  await page.waitForTimeout(300)
  assert((await names()).includes('Name'), 'Expand all brings the field back')
  await page.click(row('Greeter') + ' .tree-twist')
  await page.waitForTimeout(300)
  await open(page, 'go.mod')
  await open(page, 'main.go')
  await page.waitForFunction(() => [...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'Greeter'), null, { timeout: 8000 })
  assert(!(await names()).includes('Name'), 'the fold of main.go survives a switch to another file: ' + JSON.stringify(await names()))
  await page.click('[data-testid=structure-collapse]')
  await page.waitForTimeout(300)
  assert(!(await names()).includes('Name'), 'Collapse all folds every symbol with children')
  await page.click('[data-tool=structure] [data-testid=zone-menu]')
  await page.waitForSelector('.ctx-menu')
  // The tool has no ⋮ of its own any more: its choices come after the core items of the zone menu (#175).
  const head = await page.$$eval('.ctx-menu .ctx-item .ctx-label', (els) => els.map((e) => e.textContent.trim()))
  assert(head[0] === 'Open in a window' && head[1] === 'Close' && head[2] === 'Expand all', 'the menu of the Structure zone: ' + JSON.stringify(head))
  assert(!(await page.$('.side-right .panel-head button[title="Options"]')), 'the tool keeps no Options button of its own')
  const pkgItem = await page.$('.ctx-item:has-text("Show Package Structure")')
  assert(!!pkgItem && !(await pkgItem.evaluate((e) => e.disabled)), 'Show Package Structure is a live entry of the menu')
  assert(!(await pkgItem.evaluate((e) => e.getAttribute('aria-checked') === 'true')), 'and it is off by default')
  await page.click('.ctx-item:has-text("Sort alphabetically")')
  await page.click('[data-testid=structure-expand]')
  await page.waitForTimeout(400)
  const sorted = await names()
  const at = (n) => sorted.indexOf(n)
  assert(at('Name') === at('Greeter') + 1 && at('Greeter') < at('main'), 'the alphabetical sort reorders the file but keeps Name under Greeter: ' + JSON.stringify(sorted))
  await page.click(row('(Greeter).Hello'))
  assert(!!(await page.$('.tree-row.selected:has(.tree-name:text-is("(Greeter).Hello"))')), 'one click selects the row')
  await page.dblclick(row('(Greeter).Hello'))
  await page.waitForFunction(() => document.querySelector('[data-testid=status-cursor]')?.textContent.startsWith('8:'), null, { timeout: 5000 }).catch(() => {})
  assert((await line()).startsWith('8:'), 'a double click jumps to the symbol: ' + (await line()))
  const singleClickItem = async () => {
    await page.click('[data-tool=structure] [data-testid=zone-menu]')
    await page.waitForSelector('.ctx-menu')
    await page.click('.ctx-item:has-text("Navigate with Single Click")')
    await page.waitForTimeout(300)
  }
  await singleClickItem()
  await page.click(row('main'))
  await page.waitForFunction(() => document.querySelector('[data-testid=status-cursor]')?.textContent.startsWith('12:'), null, { timeout: 5000 }).catch(() => {})
  assert((await line()).startsWith('12:'), 'Navigate with Single Click: one click jumps: ' + (await line()))
  await singleClickItem() // back to select on click
  await page.click('[data-tool=structure] [data-testid=zone-menu]')
  await page.waitForSelector('.ctx-menu')
  await page.click('.ctx-item:has-text("Sort in the file")')
  await page.waitForTimeout(300)
  assert((await names()).join() === ['Greeter', 'Name', '(Greeter).Hello', 'main'].join(), 'Sort in the file puts the tree back in the order of the file: ' + JSON.stringify(await names()))
  // The exported / private lock (#170).
  const lockOf = async (name) => {
    const el = await page.$(row(name) + ' .sym-lock')
    if (!el) return null
    return await el.evaluate((e) => ({ cls: e.className, color: getComputedStyle(e).color }))
  }
  const menu = async (label) => {
    await page.click('[data-tool=structure] [data-testid=zone-menu]')
    await page.waitForSelector('.ctx-menu')
    await page.click(`.ctx-item:has-text("${label}")`)
    await page.waitForTimeout(300)
  }
  const locks = await Promise.all(['Greeter', 'Name', '(Greeter).Hello', 'main'].map(lockOf))
  assert(locks[0]?.cls.includes('exported') && locks[1]?.cls.includes('exported') && locks[2]?.cls.includes('exported'), 'an open lock on Greeter, its field and its method: ' + JSON.stringify(locks))
  assert(locks[3]?.cls.includes('private'), 'a closed lock on main: ' + JSON.stringify(locks[3]))
  assert(locks[0].color !== locks[3].color, 'the exported lock is green, the private one red: ' + locks[0].color + ' / ' + locks[3].color)
  await open(page, 'priv.go')
  await page.waitForFunction(() => [...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'Transport'), null, { timeout: 8000 })
  assert(!!(await lockOf('Transport'))?.cls.includes('exported') && !!(await lockOf('maxFrame'))?.cls.includes('private'), 'Transport exported, maxFrame private in priv.go')
  await menu('Sort by Exportability')
  const byExport = await names()
  assert(byExport.join() === ['Transport', 'maxFrame'].join(), 'Sort by Exportability puts Transport before maxFrame: ' + JSON.stringify(byExport))
  await menu('Show Private Members')
  assert((await names()).join() === 'Transport', 'Show Private Members unchecked hides maxFrame: ' + JSON.stringify(await names()))
  await open(page, 'main.go')
  await open(page, 'priv.go')
  await page.waitForFunction(() => [...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'Transport'), null, { timeout: 8000 })
  assert(!(await names()).includes('maxFrame'), 'the private symbols stay hidden after switching file: ' + JSON.stringify(await names()))
  await menu('Show Private Members')
  assert((await names()).join() === ['Transport', 'maxFrame'].join(), 'checked again, they come back: ' + JSON.stringify(await names()))
  await menu('Sort in the file')
  await open(page, 'main.go')
  await page.waitForFunction(() => [...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'Greeter'), null, { timeout: 8000 })
  assert((await names()).join() === ['Greeter', 'Name', '(Greeter).Hello', 'main'].join(), 'the tree of main.go is back as it was: ' + JSON.stringify(await names()))
  // Speed Search: typing in the focused tree, Ctrl+F, Escape (#171).
  const filterOpen = () => page.isVisible('[data-testid=structure-filter]')
  const selectedName = () => page.textContent('.side-right .tree-row.selected .tree-name')
  await page.click(row('main'))
  await page.keyboard.type('Nam')
  await page.waitForSelector('[data-testid=structure-filter]', { timeout: 3000 }).catch(() => {})
  assert((await names()).join() === ['Greeter', 'Name'].join(), 'typing in the tree filters it and keeps the parent of the match: ' + JSON.stringify(await names()))
  const marks = await page.$$eval('.side-right .tree-row', (e) => e.map((r) => [...r.querySelectorAll('mark')].map((m) => m.textContent).join('')))
  assert(marks.join('|') === '|Nam', 'the matched characters are highlighted in the row of the match: ' + JSON.stringify(marks))
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  assert(!(await filterOpen()), 'Escape closes the filter box')
  assert((await names()).join() === ['Greeter', 'Name', '(Greeter).Hello', 'main'].join(), 'and brings the whole tree back: ' + JSON.stringify(await names()))
  await page.keyboard.press('Control+f')
  await page.waitForTimeout(300)
  assert(await filterOpen(), 'Ctrl+F opens the filter while the tree has the focus')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  await page.click('.pane.active .ed-content')
  await page.keyboard.press('Control+f')
  await page.waitForTimeout(400)
  assert((await page.$$('.findbar')).length > 0 && !(await filterOpen()), 'Ctrl+F in the editor still opens Find in the file')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  await page.click('[data-testid=structure-search]')
  await page.waitForTimeout(300)
  assert(await filterOpen(), 'the magnifier opens the filter too')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  // Always Select Opened Element: the row of the symbol around the caret.
  await page.click('[data-tool=structure] [data-testid=zone-menu]')
  await page.waitForSelector('.ctx-menu')
  const followItem = await page.$('.ctx-item:has-text("Always Select Opened Element")')
  assert(!!followItem && !(await followItem.evaluate((e) => e.disabled)), 'the menu entry is no longer disabled')
  await followItem.click()
  await page.waitForTimeout(300)
  await caretOn('fmt.Sprintf')
  await page.waitForTimeout(600)
  assert((await selectedName()) === '(Greeter).Hello', 'the caret inside Hello selects its row: ' + (await selectedName()))
  await caretOn('func main')
  await page.waitForTimeout(600)
  assert((await selectedName()) === 'main', 'a caret in main selects main: ' + (await selectedName()))
  await page.click(row('Greeter') + ' .tree-twist')
  await page.waitForTimeout(300)
  assert(!(await names()).includes('Name'), 'the field is folded under Greeter: ' + JSON.stringify(await names()))
  await caretOn('Name string', 3)
  await page.waitForTimeout(600)
  assert(!!(await page.$(row('Greeter') + ' .tree-twist.open')), 'the caret inside the field unfolds its parent')
  assert((await selectedName()) === 'Name', 'and selects its row: ' + (await selectedName()))
  const kept = await selectedName()
  await menu('Always Select Opened Element')
  await caretOn('func main')
  await page.waitForTimeout(600)
  assert((await selectedName()) === kept, 'with the option off, the selection does not move: ' + (await selectedName()))
  // The two commands in Search Everywhere.
  const palette = async (q) => {
    await page.keyboard.press('Control+Shift+a')
    await page.waitForSelector('.pick.se .pick-input')
    await page.click('.pick.se .pick-input')
    await page.keyboard.press('Control+a')
    await page.keyboard.type(q)
    await page.waitForTimeout(300)
  }
  await palette('speed search')
  assert(!!(await page.$('.pick-item:has-text("Speed Search")')), 'structure.speedSearch is in the palette')
  await page.keyboard.press('Escape')
  await palette('always select')
  assert(!!(await page.$('.pick-item:has-text("Always Select Opened Element")')), 'structure.alwaysSelect is in the palette')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  // The package view: the sibling files of the folder as nodes (#172).
  await menu('Sort alphabetically')
  const singleAlpha = (await names()).join()
  await menu('Show Package Structure')
  await page.waitForFunction(() => [...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'priv.go'), null, { timeout: 10000 })
  const pkg = await names()
  const posOf = (n) => pkg.indexOf(n)
  assert(posOf('main.go') === 0 && posOf('priv.go') > 0 && posOf('silent.go') > posOf('priv.go') && !pkg.includes('app.php'), 'the package view lists the sibling Go files as nodes, not app.php: ' + JSON.stringify(pkg))
  assert(posOf('Silent') > posOf('silent.go'), 'silent.go, never opened in an editor, gives its symbols through the server: ' + JSON.stringify(pkg))
  assert(pkg.slice(posOf('main.go') + 1, posOf('priv.go')).join() === singleAlpha, 'the symbols of main.go keep their order under its node: ' + JSON.stringify(pkg) + ' vs ' + JSON.stringify(singleAlpha))
  assert(await page.$eval(row('priv.go') + ' .sym-glyph', (e) => e.textContent) === 'F', 'a file node carries the File glyph')
  assert(!(await page.$(row('priv.go') + ' .sym-lock')), 'a file node shows no lock')
  assert(posOf('Greeter') > posOf('main.go') && posOf('Transport') > posOf('priv.go'), 'the symbols sit under their own file: ' + JSON.stringify(pkg))
  await page.click(row('priv.go') + ' .tree-twist')
  await page.waitForTimeout(300)
  assert(!(await names()).includes('Transport'), 'the twisty folds a whole file: ' + JSON.stringify(await names()))
  await open(page, 'go.mod')
  await open(page, 'main.go')
  await page.waitForFunction(() => [...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'priv.go'), null, { timeout: 8000 })
  assert(!(await names()).includes('Transport'), 'the fold of priv.go survives a switch to another file: ' + JSON.stringify(await names()))
  await page.click('[data-testid=structure-expand]')
  await page.waitForTimeout(400)
  assert((await names()).includes('Transport') && (await names()).includes('Greeter'), 'Expand all covers every file of the package')
  await page.click('[data-testid=structure-collapse]')
  await page.waitForTimeout(400)
  assert((await names()).join() === 'main.go,priv.go,silent.go', 'Collapse all folds every file of the package: ' + JSON.stringify(await names()))
  await page.click('[data-testid=structure-expand]')
  await page.waitForTimeout(400)
  await page.dblclick(row('Transport'))
  await page.waitForFunction(() => document.querySelector('.pane.active .tab.active')?.textContent.includes('priv.go'), null, { timeout: 5000 }).catch(() => {})
  assert((await line()).startsWith('5:'), 'a double click on Transport opens priv.go at its line: ' + (await line()))
  await open(page, 'main.go')
  await page.waitForFunction(() => [...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'priv.go'), null, { timeout: 8000 })
  await menu('Sort by Exportability')
  const byFile = await names()
  assert(byFile.indexOf('priv.go') < byFile.indexOf('Transport') && byFile.indexOf('Transport') < byFile.indexOf('maxFrame'), 'Sort by Exportability applies inside each file: ' + JSON.stringify(byFile))
  assert(byFile.indexOf('main') > byFile.indexOf('(Greeter).Hello') && byFile.indexOf('main') < byFile.indexOf('priv.go'), 'and keeps main last under main.go: ' + JSON.stringify(byFile))
  await menu('Sort in the file')
  await menu('Show Private Members')
  const noPrivate = await names()
  assert(!noPrivate.includes('maxFrame') && noPrivate.includes('Transport') && noPrivate.includes('priv.go'), 'Show Private Members off hides maxFrame in the package view: ' + JSON.stringify(noPrivate))
  await menu('Show Private Members')
  await page.click('[data-testid=structure-search]')
  await page.waitForTimeout(300)
  await page.keyboard.type('max')
  await page.waitForTimeout(400)
  assert((await names()).join() === 'priv.go,maxFrame', 'Speed Search keeps the file node of a match: ' + JSON.stringify(await names()))
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  await menu('Show Package Structure')
  await page.waitForFunction(() => ![...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'priv.go'), null, { timeout: 8000 })
  assert((await names()).join() === ['Greeter', 'Name', '(Greeter).Hello', 'main'].join(), 'off, the tree is the single-file tree of #169: ' + JSON.stringify(await names()))
  await menu('Show Package Structure')
  await page.waitForFunction(() => [...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'priv.go'), null, { timeout: 8000 })
  await page.reload()
  await page.waitForSelector('.menubar')
  await page.waitForTimeout(600)
  if (!(await page.$('.side-right .tree-row'))) await page.click('.rail-right .rail-btn[title="Structure"]')
  await page.waitForFunction(() => [...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'priv.go'), null, { timeout: 10000 })
  const afterReload = await names()
  assert(afterReload.includes('main.go') && afterReload.includes('priv.go'), 'the package view is remembered across a reload: ' + JSON.stringify(afterReload))
  await open(page, 'app.php')
  await page.click('[data-tool=structure] [data-testid=zone-menu]')
  await page.waitForSelector('.ctx-menu')
  const phpItem = await page.$('.ctx-item:has-text("Show Package Structure")')
  assert(!!(await phpItem.evaluate((e) => e.disabled)) && (await phpItem.evaluate((e) => e.title)) === 'No language server for this file type', 'with no server for the file, the entry is disabled with its tooltip')
  await page.keyboard.press('Escape')
  await open(page, 'main.go')
  await menu('Show Package Structure')
  await page.waitForFunction(() => ![...document.querySelectorAll('.side-right .tree-row .tree-name')].some((x) => x.textContent === 'priv.go'), null, { timeout: 8000 })
  // Diagnostics
  await page.click('.pane.active .ed-content')
  await page.keyboard.press('Control+End')
  await page.keyboard.type('\nfunc broken() { return 1 }\n')
  const diag = await page
    .waitForFunction(() => CSS.highlights.get('diag-error')?.size, null, { timeout: 10000 })
    .then((h) => h.jsonValue(), () => 0)
  assert(diag > 0, `diagnostic underlined in the editor (${diag})`)
  if (!(await page.isVisible('[data-tool=problems]'))) await page.click('.rail-right .rail-btn[title="Problems"]')
  await page.click('[data-tool=problems] .tab:has-text("Problems")')
  await page.waitForTimeout(300)
  assert((await page.$$('.problem')).length > 0, 'the Problems panel lists the diagnostic')
  await page.screenshot({ path: OUT + '/lsp.png' })
  // Remove the broken function again.
  await page.click('.pane.active .ed-content')
  for (let i = 0; i < 3 && (await text(page)).includes('broken'); i++) await page.keyboard.press('Control+z')
  assert(!(await text(page)).includes('broken'), 'undo removes the broken function')

  // Completion after a trigger character, filtered while typing.
  await caretOn('.Hello())', 9)
  await page.keyboard.press('Enter')
  await page.keyboard.type('fmt.Pri')
  const shown = await page.waitForSelector('.completion-item', { timeout: 10000 }).then(() => true, () => false)
  if (!shown) {
    await page.screenshot({ path: OUT + '/nocompletion.png' })
    console.log('     texte : ' + JSON.stringify((await text(page)).slice(150, 330)))
    console.log('     toasts : ' + (await page.$$eval('.toast', (t) => t.map((x) => x.textContent).join(' | '))))
  }
  assert(shown, 'the completion list shows up')
  const labels = await page.$$eval('.completion-item .completion-label', (e) => e.map((x) => x.textContent))
  assert(labels[0]?.startsWith('Print'), 'filtered on "Pri": ' + labels.slice(0, 4).join(', '))
  await page.keyboard.type('ntl')
  await page.waitForTimeout(150)
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  const accepted = await text(page)
  assert(accepted.match(/\n\tfmt\.Println\b/g)?.length === 2, 'Enter inserts the suggestion ' + JSON.stringify(accepted.slice(180, 300)))
  assert(!(await page.isVisible('.completion')), 'the list closes')
  await page.screenshot({ path: OUT + '/completion.png' })
  await page.keyboard.type('("ok")')
  await page.keyboard.press('Enter')

  // Unimported package: the completion adds the import.
  await page.keyboard.type('strings.ToUpp')
  // The first completion of an unimported package indexes the standard library: retried.
  for (let i = 0; i < 15 && !(await page.$('.completion-item:has-text("ToUpper")')); i++) {
    await page.waitForTimeout(1500)
    if (!(await page.$('.completion-item'))) await page.keyboard.press('Control+Space')
  }
  await page.waitForTimeout(200)
  await page.keyboard.press('Enter')
  await page.waitForTimeout(300)
  const withImport = await text(page)
  assert(/strings\.ToUpper/.test(withImport), 'strings.ToUpper completed ' + JSON.stringify(withImport.slice(0, 40) + ' … ' + withImport.slice(180, 320)))
  assert(/import \(\s*"fmt"\s*"strings"\s*\)|"strings"/.test(withImport), 'the import of strings is added')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(200)
  assert(!(await text(page)).includes('"strings"'), 'a single undo removes the completion and the import')
  await page.keyboard.press('Shift+Home')
  await page.keyboard.press('Delete')

  // Ctrl+Space
  await page.keyboard.type('Gree')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+Space')
  const manual = await page.waitForSelector('.completion-item:has-text("Greeter")', { timeout: 8000 }).then(() => true, () => false)
  assert(manual, 'Ctrl+Space suggests Greeter')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Shift+Home')
  await page.keyboard.press('Delete')
  await page.keyboard.press('Backspace')

  // Rename (Shift+F6) across the file.
  await caretOn('type Greeter', 6)
  await page.keyboard.press('Shift+F6')
  await page.waitForSelector('.modal input')
  assert((await page.inputValue('.modal input')) === 'Greeter', 'current name suggested')
  await page.fill('.modal input', 'Saluteur')
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('.pane.active .ed-content').textContent.includes('Saluteur'), null, { timeout: 8000 }).catch(() => {})
  const renamed = await text(page)
  assert(!renamed.includes('Greeter') && (renamed.match(/Saluteur/g) ?? []).length >= 3, 'all occurrences renamed')

  // Formatting (Ctrl+Alt+L): gofmt fixes the indentation.
  await caretOn('return fmt.Sprintf', 0)
  await page.keyboard.press('Home')
  await page.keyboard.type('      ')
  await page.keyboard.press('Control+Alt+l')
  await page.waitForFunction(() => /\n\treturn fmt\.Sprintf/.test(document.querySelector('.pane.active .ed-content').textContent), null, { timeout: 8000 }).catch(() => {})
  assert(/\n\treturn fmt\.Sprintf/.test(await text(page)), 'gofmt puts the tab back')
})
