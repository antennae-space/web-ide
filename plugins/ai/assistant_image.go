// generate_image asks the image model of the settings (llm.image) for an image, or for a
// change of a page of the board or of an image of the project, and puts it on the board as a
// page (drawPage: the model receives it like any page). Behind llama-swap on one GPU, the
// request unloads the model of the conversation: no request of this conversation is in
// flight while a tool runs, and llama-swap waits for the requests of the others.

var sizeArg = regexp.MustCompile(`^\d{2,5}x\d{2,5}$`)

func (s *A) generateImage(r *assistantRun, rt *runtime.Runtime, mode string, a assistant.Args) (assistant.ToolResult, error) {
	server, model := s.LLM.ImageDefault()
	if server == "" {
		return assistant.ToolResult{}, fmt.Errorf("no image model is set (Settings > Assistant > Image generation)")
	}
	prompt := strings.TrimSpace(a.Str("prompt"))
	if prompt == "" {
		return assistant.ToolResult{}, assistant.Usagef("prompt is missing")
	}
	size := strings.TrimSpace(a.Str("size"))
	if size != "" && !sizeArg.MatchString(size) {
		return assistant.ToolResult{}, assistant.Usagef(`size is "WIDTHxHEIGHT", like "1024x1024"`)
	}
	var save string
	if p := strings.TrimSpace(a.Str("path")); p != "" {
		save = assistant.AbsPath(rt.Root, p)
		switch {
		case strings.ToLower(filepath.Ext(save)) != ".png":
			return assistant.ToolResult{}, assistant.Usagef("path is a .png file")
		case mode != engine.Build && !assistant.InZone(save, assistant.Scratch):
			return assistant.ToolResult{}, fmt.Errorf("%s mode: the image can be saved in the scratch folder %s only", mode, assistant.Scratch)
		case !assistant.InZone(save, rt.Root, assistant.Scratch):
			return assistant.ToolResult{}, fmt.Errorf("%s is outside the project", p)
		}
	}
	var edit []byte
	if e := strings.TrimSpace(a.Str("edit")); e != "" {
		var err error
		if edit, err = s.imageToEdit(r, rt, e); err != nil {
			return assistant.ToolResult{}, err
		}
	}
	data, err := s.LLM.GenerateImage(r.ctx, server, model, prompt, size, edit)
	if err != nil {
		return assistant.ToolResult{}, fmt.Errorf("%s: %v", model, err)
	}
	mime := http.DetectContentType(data)
	if !strings.HasPrefix(mime, "image/") {
		return assistant.ToolResult{}, fmt.Errorf("%s did not return an image", model)
	}
	saved := ""
	if save != "" {
		_ = rt.FS.Mkdir(path.Dir(save))
		if err := rt.FS.Write(save, data); err != nil {
			return assistant.ToolResult{}, err
		}
		if fsx.Within(rt.Root, save) {
			s.pod.Emit(r.project, "git.changed", nil)
		}
		saved = assistant.RelPath(rt.Root, save)
	}
	r.mu.Lock()
	n := len(engine.Pages(r.chat.Messages)) + 1
	r.mu.Unlock()
	origin := "an image generated by " + model
	if saved != "" {
		origin += ", saved to " + saved
	}
	src := "data:" + mime + ";base64," + base64.StdEncoding.EncodeToString(data)
	return s.drawPage(r, map[string]any{"title": a.Str("title"), "src": src, "origin": origin, "number": n})
}

// imageToEdit is the image to change: a page of the board (its PNG, else the image under it)
// or an image file of the project.
func (s *A) imageToEdit(r *assistantRun, rt *runtime.Runtime, ref string) ([]byte, error) {
	if n, err := strconv.Atoi(ref); err == nil {
		r.mu.Lock()
		pages := engine.Pages(r.chat.Messages)
		r.mu.Unlock()
		if n < 1 || n > len(pages) {
			return nil, fmt.Errorf("page %d does not exist: the board has %d pages", n, len(pages))
		}
		p := pages[n-1]
		src := p.PNG
		if src == "" && p.Doc != nil {
			var doc struct {
				Background struct{ Src string } `json:"background"`
			}
			_ = json.Unmarshal(p.Doc, &doc)
			src = doc.Background.Src
		}
		data, ok := dataURL(src)
		if !ok {
			return nil, fmt.Errorf("page %d cannot be changed: its image is not kept in the conversation", n)
		}
		return data, nil
	}
	abs := assistant.AbsPath(rt.Root, ref)
	mime := assistant.ImageTypes[strings.ToLower(filepath.Ext(abs))]
	switch {
	case !fsx.Within(rt.Root, abs):
		return nil, fmt.Errorf("%s is outside the project", ref)
	case mime == "" || mime == "image/svg+xml":
		return nil, fmt.Errorf("edit is the number of a page of the board, or the path of a png, jpg, webp or gif image of the project: %q is none of them", ref)
	}
	st, err := rt.FS.Stat(abs)
	if err != nil {
		return nil, fmt.Errorf("%s: %v", ref, err)
	}
	if st.Size > assistant.MaxImage {
		return nil, fmt.Errorf("%s is too large (%d MB, 10 MB at most)", ref, st.Size>>20)
	}
	return rt.FS.Read(abs)
}

// dataURL decodes a base64 data: URL.
func dataURL(src string) ([]byte, bool) {
	head, b64, ok := strings.Cut(src, ",")
	if !ok || !strings.HasPrefix(head, "data:") || !strings.HasSuffix(head, ";base64") {
		return nil, false
	}
	data, err := base64.StdEncoding.DecodeString(b64)
	return data, err == nil
}
