package server

import (
	"crypto/rand"
	"crypto/sha256"
	"crypto/subtle"
	"encoding/hex"
	"encoding/json"
	"errors"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"strings"
)

const (
	mcpSupervisor = "supervisor"
	mcpDeveloper  = "developer"
	mcpClients    = "mcp-clients.json"
)

// mcpGrant is operator configuration. Projects names project IDs; a true value
// includes their registered worktrees. The credential itself is never in this file.
type mcpGrant struct {
	TokenSHA256 string          `json:"tokenSha256"`
	Profile     string          `json:"profile"`
	Projects    map[string]bool `json:"projects"`
	Assistant   bool            `json:"assistant,omitempty"`
	// Additional Developer tools require an explicit plugin and tool name.
	PluginTools map[string][]string `json:"pluginTools,omitempty"`
}

type mcpIdentity struct {
	mcpGrant
	key        string
	acpSession string
	acpProject string
}

func mcpDigest(token string) string {
	sum := sha256.Sum256([]byte(token))
	return hex.EncodeToString(sum[:])
}

func (i mcpIdentity) allows(here, root string) bool {
	_, exact := i.Projects[here]
	return exact || i.Projects[root]
}

func (i mcpIdentity) matches(scope mcpScope) bool {
	return i.allows(scope.here.ID, scope.root.ID)
}

func (i mcpIdentity) grantsWorktrees() bool {
	for _, include := range i.Projects {
		if include {
			return true
		}
	}
	return false
}

func (s *Server) authenticateMCP(r *http.Request) (mcpIdentity, bool) {
	token, ok := strings.CutPrefix(r.Header.Get("Authorization"), "Bearer ")
	token = strings.TrimSpace(token)
	if !ok || len(token) < 32 || subtle.ConstantTimeCompare([]byte(token), []byte(s.Token)) == 1 {
		return mcpIdentity{}, false
	}
	if project, secret, managed := strings.Cut(token, "."); managed {
		if s.Cfg.DisableManagedMCP || !mcpProjectID.MatchString(project) {
			return mcpIdentity{}, false
		}
		if session, _, acp := strings.Cut(secret, "."); acp {
			i := mcpIdentity{mcpGrant: mcpGrant{Profile: mcpDeveloper, Projects: map[string]bool{project: false},
				Assistant: true, TokenSHA256: mcpDigest(token)}, key: "acp:" + project + ":" + session,
				acpSession: session, acpProject: project}
			if s.validACPGrant(i) {
				return i, true
			}
			return mcpIdentity{}, false
		}
		p, exists := s.Projects.Get(project)
		raw, err := s.readMCPFile("mcp-managed/" + project)
		if !exists || p.Type != "local" || err != nil || subtle.ConstantTimeCompare(raw, []byte(token)) != 1 {
			return mcpIdentity{}, false
		}
		return mcpIdentity{mcpGrant: mcpGrant{Profile: mcpDeveloper, Projects: map[string]bool{project: p.Parent == ""}, Assistant: true}, key: "managed:" + project}, true
	}
	return s.manualMCPIdentity(mcpDigest(token))
}

func (s *Server) manualMCPIdentity(hash string) (mcpIdentity, bool) {
	var grants map[string]mcpGrant
	raw, err := s.readMCPFile(mcpClients)
	if err != nil || json.Unmarshal(raw, &grants) != nil {
		return mcpIdentity{}, false
	}
	var match mcpIdentity
	for name, grant := range grants {
		if name != "" && (grant.Profile == mcpSupervisor || grant.Profile == mcpDeveloper) && len(grant.Projects) > 0 &&
			subtle.ConstantTimeCompare([]byte(hash), []byte(grant.TokenSHA256)) == 1 {
			if match.key != "" {
				return mcpIdentity{}, false
			}
			match = mcpIdentity{mcpGrant: grant, key: "client:" + name}
		}
	}
	return match, match.key != ""
}

func (s *Server) readMCPFile(name string) ([]byte, error) {
	f, err := os.Open(s.Store.Path(name))
	if err != nil {
		return nil, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() || info.Mode().Perm()&0o077 != 0 {
		return nil, errors.New("MCP credentials require a private file")
	}
	return io.ReadAll(io.LimitReader(f, 1<<20))
}

// Project IDs are generated by the registry, including the IDs of child projects.
var mcpProjectID = regexp.MustCompile(`^[a-f0-9]{12}(-[tw][a-f0-9]+)?$`)

// The pod gives the grant to session/new and session/load using its own session ID.
// A caller cannot select the ID through MCP arguments.
var mcpACPID = regexp.MustCompile(`^[a-z0-9]{12,32}$`)

func acpMCPPath(project, session string) string { return "mcp-sessions/" + project + "/" + session }

func (s *Server) validACPGrant(i mcpIdentity) bool {
	if s.Cfg.DisableManagedMCP || !mcpACPID.MatchString(i.acpSession) {
		return false
	}
	p, ok := s.Projects.Get(i.acpProject)
	if !ok || p.Type != "local" {
		return false
	}
	info, err := os.Stat(s.Store.Path("agents", i.acpProject, i.acpSession+".json"))
	if err != nil || !info.Mode().IsRegular() {
		return false
	}
	raw, err := s.readMCPFile(acpMCPPath(i.acpProject, i.acpSession))
	return err == nil && subtle.ConstantTimeCompare([]byte(i.TokenSHA256), []byte(mcpDigest(string(raw)))) == 1
}

func (s *Server) acpMCPToken(project, session string) (string, error) {
	if !mcpACPID.MatchString(session) {
		return "", errors.New("managed MCP requires a pod ACP session")
	}
	return s.issueManagedMCPToken(project, acpMCPPath(project, session), project+"."+session)
}

func (s *Server) revokeACPMCPToken(project, session string) {
	if !mcpProjectID.MatchString(project) || !mcpACPID.MatchString(session) {
		return
	}
	s.mcpCredentials.Lock()
	defer s.mcpCredentials.Unlock()
	if err := os.Remove(s.Store.Path(acpMCPPath(project, session))); err != nil && !os.IsNotExist(err) {
		log.Printf("MCP: cannot remove ACP credential: %v", err)
	}
}

func (s *Server) managedMCPToken(project string) (string, error) {
	return s.issueManagedMCPToken(project, "mcp-managed/"+project, project)
}

func (s *Server) issueManagedMCPToken(project, path, prefix string) (string, error) {
	if s.Cfg.DisableManagedMCP || !mcpProjectID.MatchString(project) {
		return "", errors.New("managed MCP is unavailable")
	}
	p, ok := s.Projects.Get(project)
	if !ok || p.Type != "local" {
		return "", errors.New("managed MCP requires a registered local project")
	}
	s.mcpCredentials.Lock()
	defer s.mcpCredentials.Unlock()
	if raw, err := s.readMCPFile(path); err == nil {
		return string(raw), nil
	} else if !os.IsNotExist(err) {
		return "", err
	}
	key := make([]byte, 32)
	if _, err := rand.Read(key); err != nil {
		return "", err
	}
	token := prefix + "." + hex.EncodeToString(key)
	return token, s.Store.WriteFile(path, []byte(token))
}
